/**
 * Generates packages/obsidian-plugin/src/data/greek-data.ts from two open sources:
 *
 *   - MorphGNT SBLGNT  https://github.com/morphgnt/sblgnt   (parsing data, CC BY-SA)
 *   - Dodson lexicon   https://github.com/biblicalhumanities/Dodson-Greek-lexicon  (CC0)
 *
 * Usage: node scripts/build-greek-data.mjs <sblgnt checkout> <dodson.xml>
 *
 * Output is one string with four sections separated by the line "===":
 *   0  parse codes, space separated           (index -> "N-----NSM-")
 *   1  lemmas, space separated                (index -> "λόγος")
 *   2  brief glosses, newline separated       (aligned to the lemma table; "" when unknown)
 *   3  surface forms, one per line: form|codes|lemmas (indices in base 36, comma separated)
 *   4  normalized forms, same shape
 *   5  the dominant part of speech of each lemma, space separated, aligned to the lemma table
 *
 * The two form tables are kept apart on purpose: normalizing collapses spellings that the corpus
 * distinguishes, so a lookup tries the exact spelling first and only then the normalized table.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const [corpusDir, dodsonXml] = process.argv.slice(2);
if (!corpusDir || !dodsonXml) {
  console.error('Usage: node scripts/build-greek-data.mjs <sblgnt checkout> <dodson.xml>');
  process.exit(2);
}

const fold = (s) =>
  s
    .normalize('NFD')
    .replace(/\p{Mn}/gu, '')
    .toLowerCase();

// ---- lexicon: lemma -> brief gloss ------------------------------------------------------------
const xml = readFileSync(dodsonXml, 'utf8');
const lexicon = new Map();
const foldedLexicon = new Map();
for (const m of xml.matchAll(/<entry n="([^"|]+)\s*\|[^"]*">\s*<orth>.*?<\/orth>\s*<def role="brief">(.*?)<\/def>/gs)) {
  const lemma = m[1].trim();
  const gloss = m[2].replace(/\s+/g, ' ').trim();
  lexicon.set(lemma, gloss);
  if (!foldedLexicon.has(fold(lemma))) foldedLexicon.set(fold(lemma), gloss);
}

// ---- corpus: form -> parses and lemmas --------------------------------------------------------
const codes = new Map(); // code -> index
const lemmas = new Map(); // lemma -> index
const lemmaPos = new Map(); // lemma -> Map(pos -> count)
const surface = new Map(); // form as written -> { codes:Set, lemmas:Set }
const normal = new Map(); // normalized form -> { codes:Set, lemmas:Set }
const idx = (map, key) => {
  let i = map.get(key);
  if (i === undefined) {
    i = map.size;
    map.set(key, i);
  }
  return i;
};
const add = (map, form, codeIdx, lemmaIdx) => {
  if (!form) return;
  let e = map.get(form);
  if (!e) map.set(form, (e = { codes: new Set(), lemmas: new Set() }));
  e.codes.add(codeIdx);
  e.lemmas.add(lemmaIdx);
};

let words = 0;
for (const file of readdirSync(corpusDir).filter((f) => f.endsWith('-morphgnt.txt')).sort()) {
  for (const line of readFileSync(path.join(corpusDir, file), 'utf8').split('\n')) {
    const p = line.split(' ');
    if (p.length < 7) continue;
    words++;
    const codeIdx = idx(codes, p[1] + p[2]);
    const lemmaIdx = idx(lemmas, p[6]);
    let posCounts = lemmaPos.get(p[6]);
    if (!posCounts) lemmaPos.set(p[6], (posCounts = new Map()));
    posCounts.set(p[1], (posCounts.get(p[1]) ?? 0) + 1);
    add(surface, p[4], codeIdx, lemmaIdx); // form as written, punctuation stripped
    add(normal, p[5], codeIdx, lemmaIdx); // normalized form
  }
}

const b36 = (n) => n.toString(36);
const lemmaList = [...lemmas.keys()];
const glossList = lemmaList.map((l) => lexicon.get(l) ?? foldedLexicon.get(fold(l)) ?? '');
const encode = (map) =>
  [...map.entries()]
    .map(([form, e]) => `${form}|${[...e.codes].map(b36).join(',')}|${[...e.lemmas].map(b36).join(',')}`)
    .sort()
    .join('\n');

// A normalized entry whose key is also a surface form can never be reached, because the exact
// lookup finds the surface entry first. Dropping those keeps the bundle small.
for (const key of [...normal.keys()]) if (surface.has(key)) normal.delete(key);

const SEP = '\n===\n';
// The part of speech a lemma is used as most often, so a glossary can leave out, say, articles.
const posList = lemmaList.map((l) => {
  const counts = [...(lemmaPos.get(l) ?? new Map())].sort((a, b) => b[1] - a[1]);
  return counts.length ? counts[0][0] : '--';
});

const blob = [
  [...codes.keys()].join(' '),
  lemmaList.join(' '),
  glossList.join('\n'),
  encode(surface),
  encode(normal),
  posList.join(' '),
].join(SEP);

const outDir = 'packages/obsidian-plugin/src/data';
mkdirSync(outDir, { recursive: true });
const header = `/* eslint-disable */
// GENERATED by scripts/build-greek-data.mjs - do not edit.
//
// Sources: MorphGNT SBLGNT parsing data (CC BY-SA, https://github.com/morphgnt/sblgnt) and the
// Dodson Greek lexicon (CC0, https://github.com/biblicalhumanities/Dodson-Greek-lexicon).
// ${words.toLocaleString()} words, ${surface.size.toLocaleString()} surface forms, ${normal.size.toLocaleString()} normalized forms, ${codes.size} parse codes,
// ${lemmaList.length.toLocaleString()} lemmas, ${glossList.filter(Boolean).length.toLocaleString()} of them with a gloss.
`;
writeFileSync(path.join(outDir, 'greek-data.ts'), `${header}\nexport const GREEK_DATA = ${JSON.stringify(blob)};\n`);
console.log(`words ${words.toLocaleString()}, surface ${surface.size.toLocaleString()}, normalized ${normal.size.toLocaleString()}, codes ${codes.size}, lemmas ${lemmaList.length.toLocaleString()}`);
console.log(`glosses matched: ${glossList.filter(Boolean).length.toLocaleString()} / ${lemmaList.length.toLocaleString()}`);
console.log(`blob ${(Buffer.byteLength(blob) / 1e6).toFixed(2)} MB`);
